"""Compile the army: roster (divisions.py) + standing orders (orders/*.json) + campaigns.json -> army.json,
then prime every agent definition in ~/.claude/agents with its standing orders block.

    python build_army.py           # build + prime
    python build_army.py --check   # build only, fail on gaps (no agent files touched)

Re-run after editing divisions.py, any orders/*.json, campaigns.json, or after installing new agents.
"""
import json, os, re, sys, time
from divisions import DIVISIONS, ASSIGN

HERE = os.path.dirname(os.path.abspath(__file__))
AGENTS_DIR = os.environ.get("CAMP_AGENTS_DIR") or os.path.expanduser("~/.claude/agents")
OUT = os.path.join(HERE, "army.json")
BEGIN, END = "<!-- WAR-CAMP:BEGIN", "<!-- WAR-CAMP:END -->"
VAULT = os.path.dirname(os.path.dirname(HERE))
CAMP = json.load(open(os.path.join(HERE, "camp.json"), encoding="utf-8"))
BIZ = " and ".join(b["name"] for b in CAMP.get("businesses", [])) or CAMP.get("org", "the business")


def frontmatter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\r?\n(.*?)\r?\n---", text, re.S)
    fm = {}
    for line in (m.group(1).splitlines() if m else []):
        k, sep, v = line.partition(":")
        if sep and re.fullmatch(r"[a-z_]+", k.strip()):
            fm[k.strip()] = v.strip().strip('"')
    return fm, text


def load_orders():
    orders = {}
    d = os.path.join(HERE, "orders")
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if f.endswith(".json"):
            orders.update(json.load(open(os.path.join(d, f), encoding="utf-8")))
    return orders


LEAD = ("\n7. **You are a general: you command, you don't solo.** On any job bigger than a few edits, "
        "plan it, split it across the specialists in your division and others (ROUTING.md), "
        "dispatch them in parallel, then validate and merge their work yourself.")


def block(a, div, general):
    general_rank = a["rank"] == "General"
    bullets = lambda xs: "\n".join(f"- {x}" for x in xs) or "- (none yet)"
    status = "Active duty" if a["status"] == "active" else "Reserve — primed, deploy on trigger"
    return f"""{BEGIN} (generated by Machine/Army/build_army.py; edit Machine/Army/orders, not here) -->
## {CAMP['army_name']} — standing orders

You serve in **{div['name']}** ({div['codename']}) of the {CAMP['army_name']}, the agent force that runs {BIZ} for the operator, {CAMP['operator']}. Callsign **{a['callsign']}** · rank {a['rank']} · {status}.

**Your role here:** {a['role']}

**Deploy me when:**
{bullets(a['triggers'])}

**I deliver:**
{bullets(a['deliverables'])}

**Cadence:** {a['cadence']} · **Report to:** {general} · **Work alongside:** {', '.join(a['pairs_with']) or '—'}

**Rules of engagement ({BIZ} work only):**
1. Before starting, read `{VAULT}\\Machine\\Army\\BRIEFING.md` (the facts: offers, prices, proof, brand, tools) and the last ~20 lines of `{VAULT}\\Machine\\Agents\\COURT_CHAT.md`.
2. Post START, BLOCKED and DONE (with output paths) to Court Chat: `- [YYYY-MM-DD HH:MM] **{a['callsign']}:** message` (append only).
3. Never send anything outward (email, DM, post, payment, deploy to a client) — return drafts; the main session checkpoints with the operator.
4. No invented facts: every claim, number or price comes from the briefing, the vault, research, or is marked PLACEHOLDER.
5. If an MCP/connector fails, try the fallback connectors listed under Tools in the briefing before calling it unavailable.
6. **Route to specialists.** When a job has parts that belong to another specialist, look them up in `{VAULT}\\Machine\\Army\\ROUTING.md` and dispatch them with the Agent tool (`subagent_type` = the agent's Name). Use opus for research, design and review; sonnet for building. Run independent parts in parallel, never put two writers on one file, and validate every result before you merge it. Don't solo a job the army has a specialist for.{LEAD if general_rank else ""}
If the task in front of you has nothing to do with {BIZ}, ignore this section.
{END}"""


def main(check=False):
    divs = {d[0]: dict(zip(("id", "name", "codename", "general", "color", "mission"), d)) for d in DIVISIONS}
    orders = load_orders()
    agents, gaps = [], []
    for div_id, ids in ASSIGN.items():
        for aid in ids:
            fm, _ = frontmatter(os.path.join(AGENTS_DIR, aid + ".md"))
            o = orders.get(aid)
            if not o:
                gaps.append(aid)
                o = {}
            general = divs[div_id]["general"] == aid
            agents.append({
                "id": aid,
                "name": fm.get("name", aid),          # = the subagent_type used to dispatch it
                "emoji": fm.get("emoji", ""),
                "color": fm.get("color", ""),
                "vibe": fm.get("vibe", ""),
                "description": fm.get("description", "")[:300],
                "division": div_id,
                "rank": "General" if general else o.get("rank", "Soldier"),
                "status": "active" if general else o.get("status", "reserve"),
                "callsign": o.get("callsign") or re.sub(r"[^A-Z0-9]+", "-", fm.get("name", aid).upper()).strip("-")[:18],
                "role": o.get("role", "Reserve specialist: deploy me when a job matches my description above."),
                "triggers": o.get("triggers", []),
                "deliverables": o.get("deliverables", []),
                "cadence": o.get("cadence", "On demand"),
                "pairs_with": o.get("pairs_with", []),
            })
    seen = {}
    for a in agents:  # callsigns must be unique: they key Court Chat lines
        seen.setdefault(a["callsign"], []).append(a["id"])
    dup_calls = [f"{c}={'/'.join(ids)}" for c, ids in seen.items() if len(ids) > 1]
    known = {a["id"] for a in agents}
    stray = sorted(set(orders) - known)
    campaigns = json.load(open(os.path.join(HERE, "campaigns.json"), encoding="utf-8")) \
        if os.path.exists(os.path.join(HERE, "campaigns.json")) else []
    rhythm = {}  # rhythm/<business>.json: that business's day-to-day battle rhythm
    rdir = os.path.join(HERE, "rhythm")
    for f in sorted(os.listdir(rdir)) if os.path.isdir(rdir) else []:
        if f.endswith(".json"):
            rhythm[f[:-5]] = json.load(open(os.path.join(rdir, f), encoding="utf-8"))
    camp_ids = {c["id"] for c in campaigns}
    bad_refs = sorted({x for c in campaigns for p in c.get("phases", []) for x in p.get("agents", []) if x not in known}
                      | {x for r in rhythm.values() for d in r.get("duties", []) for x in d.get("agents", []) if x not in known}
                      | {f"campaign:{d['campaign']}" for r in rhythm.values() for d in r.get("duties", [])
                         if d.get("campaign") and d["campaign"] not in camp_ids})

    army = {"generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "divisions": list(divs.values()), "agents": agents, "campaigns": campaigns, "rhythm": rhythm}
    json.dump(army, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    active = sum(a["status"] == "active" for a in agents)
    print(f"army.json: {len(agents)} agents ({active} active, {len(agents) - active} reserve), "
          f"{len(divs)} divisions, {len(campaigns)} campaigns")
    if gaps:
        print(f"  no written orders yet for {len(gaps)} agents (they run on their default role; /setup-camp writes them)")
    problems = (("orders for unknown agents", stray),
                ("campaign refs to unknown agents", bad_refs), ("duplicate callsigns", dup_calls))
    for label, xs in problems:
        if xs:
            print(f"  {label} ({len(xs)}): {' '.join(xs)}")
    if check:
        return 1 if any(xs for _, xs in problems) else 0

    by_id = {a["id"]: a for a in agents}
    primed = 0
    for a in agents:
        path = os.path.join(AGENTS_DIR, a["id"] + ".md")
        text = open(path, encoding="utf-8").read()
        text = re.sub(r"\n*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "\n", text, flags=re.S).rstrip()
        div = divs[a["division"]]
        g = div["general"]
        general = "CLAUDE (main session)" if a["id"] == g else f"{by_id[g]['callsign']} ({by_id[g]['name']})"
        open(path, "w", encoding="utf-8").write(text + "\n\n" + block(a, div, general) + "\n")
        primed += 1
    print(f"primed {primed} agent definitions in {AGENTS_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
